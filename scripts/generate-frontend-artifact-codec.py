#!/usr/bin/env python3
"""Generate a bounded pooled codec for persistent frontend declaration records."""
from pathlib import Path
import argparse
from snapshot_codec import generate_snapshot_codec, schema_from_sources, write_or_check
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
schema=schema_from_sources([ROOT/'src/frontend'/name for name in ['semantic_artifact.enq','semantic.enq','hir.enq','type_scope.enq','parser/statements.enq']])
imports='import refrain::frontend::hir::TypeId\nimport refrain::frontend::parser::statements::{CallParameter, ParameterDefault}\nimport refrain::frontend::semantic::{SemanticCallable, SemanticField, SemanticMethod, SemanticVariant}\nimport refrain::frontend::semantic_artifact::{CallableBinding, ModuleSemanticView, SemanticIndexArtifact}\nimport refrain::frontend::type_scope::TypeNameBinding'
text,fingerprint=generate_snapshot_codec(schema,[('SemanticIndexArtifact','ENQSI002')],imports,
    'Generated by scripts/generate-frontend-artifact-codec.py; edit the generator/schema.')
write_or_check(ROOT/'src/frontend/semantic_codec.enq',text,args.check)
print('Frontend snapshots;',len(text),'bytes;',fingerprint)

# Body records use the same bounded pooled wire primitives. The declaration
# schema above stays independent: replay evolution does not change index keys.
replay_schema=schema_from_sources([ROOT/'src/frontend/semantic_artifact.enq',ROOT/'packages/json/src/lib.enq'])
text,fingerprint=generate_snapshot_codec(replay_schema,[('SemanticModuleRecord','ENQSR001')],
    'import json::Json\nimport refrain::frontend::semantic_artifact::SemanticModuleRecord',
    'Generated by scripts/generate-frontend-artifact-codec.py; edit the generator/schema.')
write_or_check(ROOT/'src/frontend/semantic_replay_codec.enq',text,args.check)
print('Semantic replay snapshots;',len(text),'bytes;',fingerprint)
