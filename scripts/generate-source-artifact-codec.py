#!/usr/bin/env python3
"""Generate bounded strict-syntax snapshots, independent of native layout."""
from pathlib import Path
import argparse
from snapshot_codec import generate_snapshot_codec, schema_from_sources, write_or_check
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
paths=['source_artifact.enq','analysis.enq','lexer/token.enq','parser/statements.enq','dependency_graph/mod.enq']
schema=schema_from_sources([ROOT/'src/frontend'/name for name in paths])
imports="""import refrain::frontend::analysis::{DiagnosticLabel, DiagnosticLabelKind, DiagnosticSuggestion, FrontendCallable, FrontendDiagnostic, FrontendDocument, FrontendSymbol, SuggestionApplicability}
import refrain::frontend::dependency_graph::{DependencyEdge, DependencyGraph}
import refrain::frontend::lexer::{Token, TokenType}
import refrain::frontend::parser::*
import refrain::frontend::source_artifact::ParsedSourceArtifact"""
text,fingerprint=generate_snapshot_codec(schema,[('ParsedSourceArtifact','ENQSA001')],imports,
    'Generated by scripts/generate-source-artifact-codec.py; edit the generator/schema.')
write_or_check(ROOT/'src/frontend/source_codec.enq',text,args.check)
print('Source snapshots;',len(text),'bytes;',fingerprint)
