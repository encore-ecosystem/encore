"""Generate bounded positional snapshot codecs from an explicit record schema.

Shared by EHIR bodies and frontend declaration snapshots. No native object
layout, pointer or Python runtime information enters a serialized artifact.
"""
import hashlib,json,re

def generate_snapshot_codec(schema, roots, imports, description):
    SCHEMA=schema
    PRIMITIVES={'str','bool','usize','u32','u64'}
    TYPES=set()
    def tuple_fields(typ):
        if not (typ.startswith('(') and typ.endswith(')')):return None
        fields=[];start=1;depth=0
        for index,ch in enumerate(typ[1:-1],1):
            if ch in '[(':depth+=1
            elif ch in '])':depth-=1
            elif ch==',' and depth==0:
                fields.append(typ[start:index].strip());start=index+1
        fields.append(typ[start:-1].strip())
        assert len(fields)>=2 and all(fields),typ
        return fields
    def require(typ):
        if typ in PRIMITIVES or typ in TYPES:return
        TYPES.add(typ)
        m=re.fullmatch(r'(Vec|Option)\[(.+)\]',typ)
        if m:require(m[2]);return
        if typ.endswith('<H>'):require(typ[:-3]);return
        fields=tuple_fields(typ)
        if fields:
            for field in fields:require(field)
            return
        assert typ in SCHEMA,typ
        for _,field in SCHEMA[typ][1]:
            if field:require(field)
    for typ,_ in roots:require(typ)
    projection={key:SCHEMA[key] for key in sorted(TYPES) if key in SCHEMA}
    fingerprint=hashlib.sha256(json.dumps({'codec':'positional-le-string-pool-2','records':projection},sort_keys=True,separators=(',',':')).encode()).hexdigest()
    def identifier(typ):
        if '(' in typ:return 'tuple_'+hashlib.sha256(typ.encode()).hexdigest()[:20]
        return typ.replace('[','_').replace(']','').replace('<H>','_heap')
    def write(typ,value):return f'write_{identifier(typ)}(writer, {value})'
    def read(typ):return f'read_{identifier(typ)}(reader)?'
    header='''//! Generated by scripts/generate-ehir-artifact-codec.py; edit the generator/schema.
    //! Positional little-endian records, independent of host layout and addresses.
    import core::fmt::Debug
    import core::option::Option
    import core::result::Result
    import std::vec::Vec
    import mod::core::*

    extern fn encore_str_data(value: str) -> u8*
    extern fn encore_codec_string(bytes: u8*, len: usize) -> str
    extern fn encore_codec_utf8_valid(bytes: u8*, len: usize) -> bool
    extern fn memcpy(destination: u8*, source: u8*, len: usize) -> u8*

    extern fn encore_codec_read_u32_le(source: u8*) -> u32
    extern fn encore_codec_read_u64_le(source: u8*) -> u64
    extern fn encore_codec_write_u32_le(destination: u8*, value: u32) ->()
    extern fn encore_codec_write_u64_le(destination: u8*, value: u64) ->()

    extern fn encore_strmap_new() -> usize
    extern fn encore_strmap_get(index: usize, key: str) -> usize
    extern fn encore_strmap_put(index: usize, key: str, value: usize) ->()
    extern fn encore_strmap_free(index: usize) ->()
    struct SnapshotWriter { bytes: Vec[u8], failed: bool, depth: usize, strings: usize, string_count: usize, failure: str }
    struct SnapshotReader { bytes: Vec[u8], cursor: usize, depth: usize, allocated: usize, strings: Vec[str], allocation_limit: usize }
    fn writer_fail(writer: mut SnapshotWriter, message: str) ->() {
        if !writer.failed { writer.failure = message }
        writer.failed = true
    }

    #attr(safe)
    fn snapshot_pointer(bytes: Vec[u8], offset: usize) -> u8* {
        let base = bytes.as_ptr()
        unsafe {
            unsafe ehir { pointer: u8* = gep base: u8*, offset: usize }
            ret pointer
        }
    }
    fn writer_enter(writer: mut SnapshotWriter) -> bool {
        if writer.failed || writer.depth >= 128_usize { writer_fail(writer, "nesting") ret false }
        writer.depth += 1_usize ret true
    }
    fn reader_enter(reader: mut SnapshotReader) -> Result[(), str] {
        if reader.depth >= 128_usize { ret Result::Err("EHIR snapshot nesting limit") }
        reader.depth += 1_usize ret Result::Ok(())
    }
    fn write_u8(writer: mut SnapshotWriter, value: u8) ->() {
        if writer.failed || writer.bytes.len() >= 67108864_usize { writer_fail(writer, "size") ret() }
        writer.bytes.push(value)
    }
    fn read_u8(reader: mut SnapshotReader) -> Result[u8, str] {
        if reader.cursor >= reader.bytes.len() { ret Result::Err("truncated EHIR snapshot") }
        let value = reader.bytes.get_unchecked_borrowed(reader.cursor)
        reader.cursor += 1_usize ret Result::Ok(value)
    }
    fn write_u32(writer: mut SnapshotWriter, value: u32) ->() {
        if writer.failed || writer.bytes.len() > 67108864_usize - 4_usize { writer_fail(writer, "size") ret() }
        let start = writer.bytes.len()
        writer.bytes.reserve(4_usize)
        unsafe { encore_codec_write_u32_le(snapshot_pointer(writer.bytes, start), value) }
        writer.bytes.set_len(start + 4_usize)
    }
    fn read_u32(reader: mut SnapshotReader) -> Result[u32, str] {
        if reader.bytes.len() - reader.cursor < 4_usize { ret Result::Err("truncated EHIR snapshot") }
        let value = unsafe { encore_codec_read_u32_le(snapshot_pointer(reader.bytes, reader.cursor)) }
        reader.cursor += 4_usize ret Result::Ok(value)
    }
    fn write_u64(writer: mut SnapshotWriter, value: u64) ->() {
        if writer.failed || writer.bytes.len() > 67108864_usize - 8_usize { writer_fail(writer, "size") ret() }
        let start = writer.bytes.len()
        writer.bytes.reserve(8_usize)
        unsafe { encore_codec_write_u64_le(snapshot_pointer(writer.bytes, start), value) }
        writer.bytes.set_len(start + 8_usize)
    }
    fn read_u64(reader: mut SnapshotReader) -> Result[u64, str] {
        if reader.bytes.len() - reader.cursor < 8_usize { ret Result::Err("truncated EHIR snapshot") }
        let value = unsafe { encore_codec_read_u64_le(snapshot_pointer(reader.bytes, reader.cursor)) }
        reader.cursor += 8_usize ret Result::Ok(value)
    }
    fn write_usize(writer: mut SnapshotWriter, value: usize) ->() { write_u64(writer, value as u64) }
    fn read_usize(reader: mut SnapshotReader) -> Result[usize, str] {
        let value = read_u64(reader)?
        if (value as usize) as u64 != value { ret Result::Err("EHIR integer exceeds host size") }
        ret Result::Ok(value as usize)
    }
    fn write_bool(writer: mut SnapshotWriter, value: bool) ->() { write_u8(writer, if value { 1_u8 } else { 0_u8 }) }
    fn read_bool(reader: mut SnapshotReader) -> Result[bool, str] {
        let value = read_u8(reader)?
        if value > 1_u8 { ret Result::Err("invalid EHIR boolean") }
        ret Result::Ok(value == 1_u8)
    }
    fn write_raw(writer: mut SnapshotWriter, value: str) ->() {
        if writer.failed || value.byte_len() > 67108864_usize - writer.bytes.len() { writer_fail(writer, "size") ret() }
        let start = writer.bytes.len()
        writer.bytes.reserve(value.byte_len())
        if value.byte_len() != 0_usize {
            unsafe { let _copied = memcpy(snapshot_pointer(writer.bytes, start), encore_str_data(value), value.byte_len()) }
            writer.bytes.set_len(start + value.byte_len())
        }
    }
    fn write_str(writer: mut SnapshotWriter, value: str) ->() {
        if writer.failed { ret() }
        let found = unsafe { encore_strmap_get(writer.strings, value) }
        if found != 0_usize { write_u32(writer, found as u32) ret() }
        if writer.string_count >= 1048576_usize || value.byte_len() > 67108864_usize {
            writer_fail(writer, "string table") ret()
        }
        writer.string_count += 1_usize
        unsafe { encore_strmap_put(writer.strings, value, writer.string_count) }
        write_u32(writer, 0_u32) write_u32(writer, value.byte_len() as u32) write_raw(writer, value)
    }
    fn read_str(reader: mut SnapshotReader) -> Result[str, str] {
        let reference = read_u32(reader)? as usize
        if reference != 0_usize {
            match reader.strings.get(reference - 1_usize) {
                Some(value) => { ret Result::Ok(value) }
                None => { ret Result::Err("invalid EHIR string reference") }
            }
        }
        let len = read_u32(reader)? as usize
        if len > reader.bytes.len() - reader.cursor || reader.allocated > reader.allocation_limit - 64_usize ||
            len > reader.allocation_limit - 64_usize - reader.allocated || reader.strings.len() >= 1048576_usize {
            ret Result::Err("invalid EHIR string length")
        }
        reader.allocated += len + 64_usize
        let pointer = snapshot_pointer(reader.bytes, reader.cursor)
        if !unsafe { encore_codec_utf8_valid(pointer, len) } { ret Result::Err("invalid EHIR string encoding") }
        let value = unsafe { encore_codec_string(pointer, len) }
        reader.strings.push(value)
        reader.cursor += len ret Result::Ok(value)
    }
    fn write_count(writer: mut SnapshotWriter, count: usize) ->() {
        if count > 1048576_usize { writer_fail(writer, "collection") ret() }
        write_u32(writer, count as u32)
    }
    fn read_count(reader: mut SnapshotReader, element_bytes: usize) -> Result[usize, str] {
        let count = read_u32(reader)? as usize
        if count > 1048576_usize || count > reader.bytes.len() - reader.cursor ||
            count > (reader.allocation_limit - reader.allocated) / element_bytes { ret Result::Err("EHIR collection limit") }
        reader.allocated += count * element_bytes ret Result::Ok(count)
    }
    fn new_snapshot_writer(magic: str, identity: str) -> SnapshotWriter {
        let index = unsafe { encore_strmap_new() }
        let mut writer = SnapshotWriter { Vec[u8]::with_capacity(1024_usize), index == 0_usize, 0_usize, index, 0_usize, "string table allocation" }
        write_raw(writer, magic) write_str(writer, "SCHEMA_FINGERPRINT") write_str(writer, identity)
        ret writer
    }
    fn new_snapshot_reader(payload: Vec[u8], magic: str, identity: str) -> Result[SnapshotReader, str] {
        if payload.len() < 8_usize || payload.len() > 67108864_usize { ret Result::Err("invalid EHIR snapshot length") }
        for index in 0_usize..8_usize {
            if payload.get_unchecked_borrowed(index) != magic.byte_at(index) { ret Result::Err("unsupported EHIR snapshot schema") }
        }
        // A bundle aggregates hundreds of bounded modules; preserve the full
        // adapter while incremental callers normally decode one body/module.
        let budget = if magic == "ENQTB002" { 1073741824_usize } else { 268435456_usize }
        let mut reader = SnapshotReader { payload, 8_usize, 0_usize, 0_usize, Vec[str]::new(), budget }
        if read_str(reader)? != "SCHEMA_FINGERPRINT" || read_str(reader)? != identity {
            ret Result::Err("EHIR snapshot schema or identity mismatch")
        }
        ret Result::Ok(reader)
    }
    '''.replace("SCHEMA_FINGERPRINT",fingerprint).replace("import mod::core::*", imports).replace("Generated by scripts/generate-ehir-artifact-codec.py; edit the generator/schema.", description)
    lines=[header]
    for typ in sorted(TYPES):
        name=identifier(typ);m=re.fullmatch(r'(Vec|Option)\[(.+)\]',typ)
        qualification='' if typ.startswith('(') else 'frozen '
        w=[f'fn write_{name}(writer: mut SnapshotWriter, value: {qualification}{typ}) ->() {{','    if !writer_enter(writer) { ret() }']
        r=[f'fn read_{name}(reader: mut SnapshotReader) -> Result[{typ}, str] {{','    reader_enter(reader)?']
        if m:
            container,inner=m.groups()
            if container=='Vec':
                w += ['    write_count(writer, value.len())',f'    for item in value {{ {write(inner,"item")} }}']
                # Dense selection ordinals are host-size-independent integers,
                # not 256-byte records. Keep conservative record accounting and
                # charge scalar vectors by their maximum supported host width.
                weight={'usize':8,'u64':8,'u32':4,'bool':1,'str':8}.get(inner,256)
                r += [f'    let count = read_count(reader, {weight}_usize)?',f'    let mut value = Vec[{inner}]::with_capacity(count)',f'    for _index in 0_usize..count {{ value.push({read(inner)}) }}']
            else:
                w += ['    match value {',f'        Some(item) => {{ write_u8(writer, 1_u8) {write(inner,"item")} }}','        None => { write_u8(writer, 0_u8) }','    }']
                r += ['    let tag = read_u8(reader)?',f'    let value = if tag == 0_u8 {{ Option[{inner}]::None }} elif tag == 1_u8 {{ Option[{inner}]::Some({read(inner)}) }}',f'        else {{ ret Result::Err("invalid EHIR optional tag") }}']
        elif typ.endswith('<H>'):
            base=typ[:-3];kind,values=SCHEMA[base];assert kind=='struct',typ
            fields=', '.join('value.'+field for field,_ in values)
            w += [f'    {write(base,base+" { "+fields+" }")}']
            r += [f'    let value = {read(base)}',f'    let value = {typ} {{ '+fields+' }']
        elif tuple_fields(typ):
            fields=tuple_fields(typ)
            for index,field in enumerate(fields):w += [f'    {write(field,"value."+str(index))}']
            r += ['    let value = ('+', '.join(read(field) for field in fields)+')']
        else:
            kind,values=SCHEMA[typ]
            if kind=='struct':
                for field,field_type in values:w += [f'    {write(field_type,"value."+field)}']
                r += [f'    let value = {typ} {{ '+', '.join(read(field_type) for _,field_type in values)+' }']
            else:
                assert len(values)<256,typ
                w += ['    match value {'];r += ['    let tag = read_u8(reader)?','    let value = match tag {']
                for tag,(variant,payload) in enumerate(values):
                    if payload:
                        w += [f'        {variant}(item) => {{ write_u8(writer, {tag}_u8) {write(payload,"item")} }}']
                        r += [f'        {tag}_u8 => {typ}::{variant}({read(payload)})']
                    else:
                        w += [f'        {variant} => {{ write_u8(writer, {tag}_u8) }}'];r += [f'        {tag}_u8 => {typ}::{variant}']
                w += ['    }'];r += ['        _ => { ret Result::Err("invalid EHIR variant tag") }','    }']
        w += ['    writer.depth -= 1_usize','}'];r += ['    reader.depth -= 1_usize','    ret Result::Ok(value)','}']
        lines.extend(['\n'.join(w),'\n'.join(r)])
    for typ,magic in roots:
        name=identifier(typ)
        lines.append(f'''pub fn encode_snapshot_{name}(value: {typ}, identity: str) -> Result[Vec[u8], str] {{
        let mut writer = new_snapshot_writer("{magic}", identity)
        write_{name}(writer, value)
        unsafe {{ encore_strmap_free(writer.strings) }}
        if writer.failed {{ ret Result::Err("EHIR snapshot " + writer.failure + " limit (" + Debug::fmt(writer.bytes.len()) + " bytes)") }}
        ret Result::Ok(writer.bytes)
    }}
    pub fn decode_snapshot_{name}(bytes: Vec[u8], identity: str) -> Result[{typ}, str] {{
        let mut reader = new_snapshot_reader(bytes, "{magic}", identity)?
        let value = read_{name}(reader)?
        if reader.cursor != reader.bytes.len() {{ ret Result::Err("trailing EHIR snapshot bytes") }}
        ret Result::Ok(value)
    }}''')
    return '\n\n'.join(lines)+'\n',fingerprint

def schema_from_sources(paths):
    schema={}
    for path in paths:
        for kind,name,body in re.findall(r'pub (struct|enum) (\w+)\s*\{([^}]+)\}',path.read_text()):
            lines=[re.sub(r'//.*','',line).strip().rstrip(',') for line in body.splitlines()]
            lines=[line for line in lines if line]
            if kind=='struct':
                fields=[line.split(':',1) for line in lines]
                assert all(len(field)==2 for field in fields),(name,lines)
                values=[(field.strip(),typ.strip()) for field,typ in fields]
            else:
                values=[]
                for line in lines:
                    match=re.fullmatch(r'(\w+)(?:\((.+)\))?',line);assert match,(name,line)
                    values.append((match[1],match[2]))
            assert name not in schema,name
            schema[name]=(kind,values)
    return schema

def write_or_check(output, text, check):
    def tokens(source):
        pattern=r'"(?:\\.|[^"\\])*"|//[^\n]*|[A-Za-z_][A-Za-z_0-9]*|[0-9][A-Za-z_0-9]*|[^\s]'
        found=[part for part in re.findall(pattern,source) if not part.startswith('//')]
        return [part for i,part in enumerate(found) if not (part==',' and i+1<len(found) and found[i+1] in ')]}')]
    if check:assert tokens(output.read_text())==tokens(text),f'{output} is stale; regenerate it'
    else:output.write_text(text)
