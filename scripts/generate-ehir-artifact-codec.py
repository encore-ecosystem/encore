#!/usr/bin/env python3
"""Generate the private EHIR codec from the typed core schema."""
from pathlib import Path
import argparse
from snapshot_codec import generate_snapshot_codec, schema_from_sources, write_or_check

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/'packages/ehir-core/src/artifact_codec.enq'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
schema=schema_from_sources(sorted((ROOT/'packages/ehir-core/src/core').glob('*.enq')))
text,fingerprint=generate_snapshot_codec(schema,[('Module','ENQTM002'),('FnDirective','ENQTF002'),('ModuleBundle','ENQTB002')],
    'import mod::core::*','Generated by scripts/generate-ehir-artifact-codec.py; edit the generator/schema.')
write_or_check(OUTPUT,text,args.check)
print('EHIR snapshots;',len(text),'bytes;',fingerprint)
