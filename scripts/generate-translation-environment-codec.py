#!/usr/bin/env python3
"""Generate the private immutable lowering-environment codec."""
from pathlib import Path
import argparse
from snapshot_codec import generate_snapshot_codec, schema_from_sources, write_or_check
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
schema=schema_from_sources([ROOT/'src/frontend/translator_environment.enq',ROOT/'src/frontend/parser/statements.enq'])
text,fingerprint=generate_snapshot_codec(schema,[('TranslationEnvironmentArtifact','ENQTE002')],
    'import refrain::frontend::translator_environment::*\nimport refrain::frontend::parser::statements::{CallParameter, ParameterDefault}',
    'Generated by scripts/generate-translation-environment-codec.py; edit the generator/schema.')
write_or_check(ROOT/'src/frontend/translator_environment_codec.enq',text,args.check)
print('Lowering environment;',len(text),'bytes;',fingerprint)
